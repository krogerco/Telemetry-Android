package com.kroger.telemetry.tracing

/**
 * Marks the transitional realtime API: live span callbacks for vendor SDKs that must be driven while work happens.
 * Only vendor adapter modules should need to opt in. Removing this tier never affects the core tracing API.
 */
@RequiresOptIn(
    level = RequiresOptIn.Level.ERROR,
    message = "Realtime span listeners are transitional and best-effort. They may be removed in a future release.",
)
@Retention(AnnotationRetention.BINARY)
@Target(
    AnnotationTarget.CLASS,
    AnnotationTarget.FUNCTION,
    AnnotationTarget.PROPERTY,
    AnnotationTarget.TYPEALIAS,
)
public annotation class RealtimeTracingApi
